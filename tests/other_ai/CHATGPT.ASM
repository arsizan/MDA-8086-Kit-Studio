.MODEL SMALL
.STACK 100H
.DATA
PATTERN DB 3CH, 42H, 81H, 81H
        DB 0FFH, 81H, 81H, 81H
.CODE
MAIN PROC
    MOV AX, @DATA
    MOV DS, AX
    MOV DX, 06H
    MOV AL, 80H
    OUT DX, AL
AGAIN:
    MOV SI, OFFSET PATTERN
    MOV CX, 8
NEXT_ROW:
    MOV DX, 00H
    MOV AL, [SI]
    OUT DX, AL
    MOV DX, 02H
    MOV AL, 01H
    OUT DX, AL
    CALL DELAY
    INC SI
    LOOP NEXT_ROW
    JMP AGAIN
DELAY PROC
    PUSH CX
    MOV CX, 0FFFFH
WAIT1:
    LOOP WAIT1
    POP CX
    RET
DELAY ENDP
MAIN ENDP
END MAIN
